-- কাঠামো এমনভাবেই বানানো, যাতে একই দোকানে একাধিক "owner" রাখা যায় —
-- owner হওয়া মানে শুধু profiles টেবিলের role = 'owner' হওয়া,
-- তাই ভবিষ্যতে যতজন খুশি মালিক যোগ/বাদ/পরিবর্তন করা যাবে এই একই পদ্ধতিতে।

-- ধাপ ১: যাকে দ্বিতীয় মালিক বানাবেন, তাকে আগে সাইটের সাইনআপ ফর্ম দিয়ে
--        সাধারণভাবে সাইনআপ করতে বলুন (এতে তার একটা নতুন/আলাদা shop তৈরি হয়ে যাবে,
--        সেটা আমরা পরের ধাপে মূল দোকানের সাথে যুক্ত করে দেব)

-- ধাপ ২: নিচের কোয়েরি দিয়ে তার ইমেইল থেকে user id বের করুন
select id as new_owner_user_id, email from auth.users where email = 'দ্বিতীয় মালিকের ইমেইল বসান';

-- ধাপ ৩: তার auto-তৈরি হওয়া আলাদা shop_id বের করুন (এটা মুছে ফেলা হবে)
select id as extra_shop_id from shops where owner_id = 'ধাপ ২ থেকে পাওয়া user_id বসান';

-- ধাপ ৪: তাকে মূল দোকানের owner বানিয়ে দিন
--        (MAIN_SHOP_ID = আপনার আসল দোকানের shops.id, এটা shops টেবিল থেকে দেখে নিন)
update profiles
set shop_id = 'আপনার মূল দোকানের shop_id বসান',
    role = 'owner'
where id = 'ধাপ ২ থেকে পাওয়া user_id বসান';

-- ধাপ ৫: তার জন্য অটো-তৈরি হওয়া অপ্রয়োজনীয় shop টা মুছে ফেলুন
delete from shops where id = 'ধাপ ৩ থেকে পাওয়া extra_shop_id বসান';

-- ব্যস, এখন দুজনেই নিজ নিজ ইমেইল/পাসওয়ার্ড দিয়ে লগইন করলে একই দোকানের
-- সব ডেটা (পণ্য, বিক্রি, বাকির খাতা) full owner অ্যাক্সেস নিয়ে দেখতে/এডিট করতে পারবেন।

-- পরে কাউকে owner থেকে সরিয়ে সাধারণ ব্যবহারকারী বানাতে চাইলে:
-- update profiles set role = 'staff' where id = 'তার user_id';
-- (এই সিস্টেমে এখনো staff-এর জন্য আলাদা পেজ-ভিত্তিক পারমিশন কনফিগার করা নেই —
--  role শুধু owner/staff এই দুই ধরনের, চাইলে সেটা পরের ধাপে যোগ করে দিতে পারি)